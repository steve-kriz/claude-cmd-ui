// Scenario (edge): a lane removed from config drops its cards into unknown next render
// ===========================================================================
test('Scenario (edge): a user lane removed from config sends its orphaned cards to unknown on the next render', () => {
  // Given a first render with a ux-review lane holding a ux-review ticket.
  const withUx = { columns: [{ status: 'ux-review' }] };
  const { mod, tab } = fresh({
    config: withUx,
    tickets: ticketsMap([{ fm: { id: 'TASK-9', title: 'p', status: 'ux-review' } }]),
  });
  mod.renderTasksBoard(tab);
  assert.deepEqual(cardStatuses(lane(tab, 'ux-review')), ['ux-review']);
  // When the ux-review column is removed from config and the board re-renders,
  // the now-orphaned ux-review ticket falls into the unknown lane (config-aware
  // routing no longer recognises the status).
  tab.tasks.config = null;
  mod.renderTasksBoard(tab);
  assert.ok(!lane(tab, 'ux-review'), 'the ux-review lane is gone after config removal');
  assert.deepEqual(cardStatuses(lane(tab, 'unknown')), ['ux-review'],
    'the orphaned card falls to unknown, not todo');
});
